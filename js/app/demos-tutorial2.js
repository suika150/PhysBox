// ── 82 豆電球の電流−電圧グラフ ─────────────────────────────
//   ★ゆっくりした交流（0.2 Hz）で電圧を上げ下げし、回路グラフの「電流−電圧」で特性曲線を描く。
//     抵抗は直線（オームの法則）、豆電球は熱くなるほど抵抗が増えて曲がる（circuit.js の bulb の注）。
//   ★豆電球の熱の時定数は 0（温度がいつもその電圧でのつり合いの値）＝曲線が1本になる。
//     0.12（既定）に戻すと、上げるときと下げるときで道がずれて輪になる、を最後に見せる。
function demoTut2IV() {
  const cy = tutTopBegin();
  const L = tutScreenX(600), R = tutScreenX(930), T = cy - 40, B = cy + 180;
  tutWires([[L, B], [L, T]], { 0:{ type:'acsource', o:{ V:5, freq:0.2, r:0 }, len:90 } });
  tutWires([[L, T], [(L + R) / 2, T], [R, T]],
    { 0:{ type:'resistor', o:{ R:8 }, len:70 }, 1:{ type:'bulb', o:{ tau:0 }, len:60 } });
  tutWires([[R, T], [R, B], [L, B]]);
  demoLabel((L * 3 + R) / 4 - 10, T - 50, 'R', '#ffd54f', 24);
  tutText('82 豆電球の電流−電圧グラフ', [
    'ゆっくりした交流（0.2 Hz）で、電圧が上がったり下がったりする',
    '1. {btn-play} → 豆電球がゆっくり明るくなったり暗くなったりする',
    '2. 抵抗 R と 豆電球 をそれぞれ右クリック →「グラフに追加」',
    '3. 窓の「電流−電圧」にチェック → 横が電圧・縦が電流のグラフ',
    '　 R … 原点を通る直線（電流は電圧に比例）',
    '　 豆電球 … 電圧を上げるほど電流が増えにくく、曲がる',
    '　 （フィラメントが熱くなるほど抵抗が大きくなる）',
    '4. 豆電球の「熱の時定数 τ」を 0.12 にすると、',
    '　 上げるときと下げるときで道がずれて、輪になる']);
}

// ── 83 大気圧を変える ──────────────────────────────────
//   ★蓋が自由な器の気体は、まわりの大気圧（＋蓋の重さ）とつり合う圧力になる。
//     「水深10m」（2気圧）で体積は等温なら半分、「真空」で膨張しきる（sim-popover.js のプリセット）。
//   ★器の壁は既定で熱を通さない＝そのまま変えると断熱変化になる。実測（体積 108 L から 2気圧へ）：
//       等温（気体のパネルの「等温」を押してから） 53.8 L・20.0℃ ＝ ちょうど半分（ボイルの法則）
//       そのまま（断熱）                           65.7 L・84.5℃ ＝ 0.608 倍（2^(−1/γ)、γ=1.4）
//     だから等温を先に押させ、断熱は比べる側として最後に回す。
function demoTut2Atm() {
  const gy = tutBegin();
  const cx = tutScreenX(800), len = 360;
  const v = createPistonVessel({ x:cx, y:gy - VESSEL_WALL_PX - len / 2, bore:150, innerLen:len, fill:0.4,
    angle:0, cylinderColor:'#546e7a', pistonColor:'#ffb74d', label:'気体' });
  v.cylinder().setStatic(true);
  gasManualVolumeChange(v.chamber());
  tutText('83 大気圧を変える', [
    '器の中の気体（水色）は、外の大気に蓋を押されてつり合っている',
    '1. {t-pointer} ボタンで気体を選び、パネルの「等温」を押す',
    '　 （温度を 20 ℃ に保つ）。圧力 P と 体積 V を見ておく',
    '2. 上の シミュレーション →「大気圧」→「水深10m」（2気圧）',
    '3. {btn-play} → 蓋が押し下げられ、体積がちょうど半分になる',
    '　 （温度が同じなら、圧力が2倍で体積は半分：ボイルの法則）',
    '4. 「地上 1atm」に戻すと元の体積に戻る',
    '5. 今度は「断熱」を押してから「水深10m」→ 体積は 0.6 倍までしか',
    '　 減らず、温度が上がる（押し縮めた仕事で温まる）',
    '6. 「真空」にすると、気体は蓋を押し上げて膨張しきる',
    '',
    '（大気圧は、別のデモを開くと 1atm に戻る）']);
}

// ── 84 熱放射（触れずに熱が伝わる）─────────────────────────
