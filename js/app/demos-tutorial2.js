// ── 回路の部品 ─────────────────────────────────────────
//   ★回路の回は、組むのに手間のかかる輪（導線と電源）を置いておき、その回の主役の素子だけを
//     生徒に入れさせる（入れ方は23：導線の上の ○ を2つクリック）。
//   ★素子どうしは端の点を共有してつながる（circuit.js の NODE_MERGE_PX）。辺の途中に素子を
//     入れるときは、導線 → 素子 → 導線 と端をそろえて並べる。
function tutC(type, ax, ay, bx, by, o) {
  const e = new CircuitElement(type, ax, ay, bx, by);
  Object.assign(e, o || {});
  circuitElements.push(e);
  return e;
}
// 折れ線 pts を導線でつなぐ。parts[i] = { type, o, len } があれば、i 番目の辺のまん中に
//   長さ len の素子を入れる（向きは辺の向き：1点目が a 端＝電源なら＋極）。返り値は parts と同じ添字の素子
function tutWires(pts, parts) {
  const out = {};
  parts = parts || {};
  for (let i = 0; i + 1 < pts.length; i++) {
    const [x1, y1] = pts[i], [x2, y2] = pts[i + 1], p = parts[i];
    if (!p) { tutC('wire', x1, y1, x2, y2); continue; }
    const L = Math.hypot(x2 - x1, y2 - y1), h = (p.len || 90) / 2 / L;
    const mx = (x1 + x2) / 2, my = (y1 + y2) / 2, dx = x2 - x1, dy = y2 - y1;
    const ax = mx - dx * h, ay = my - dy * h, bx = mx + dx * h, by = my + dy * h;
    tutC('wire', x1, y1, ax, ay);
    out[i] = tutC(p.type, ax, ay, bx, by, p.o);
    tutC('wire', bx, by, x2, y2);
  }
  return out;
}

