// ── 43 歯車コートでラックをつくる ──────────────────────────
//   ★歯車コートは面に歯を刻む（gear-tools.js）。直線の面はラックになる。
//     棒は摩擦 0（合成は積なので床とも摩擦なし）で、歯車に押されるまま横へ動く。
//   ★歯車は描かせる（27 と同じ操作）。ラックの歯に重なるように描けば吸い付いて
//     かみ合う位置に置き直される（gear.js の gearMeshPose：ラックは半径無限大の外歯車）。
//     点線の円は歯数 20（モジュール 10cm・半径 1m）の目安で、ラックの基準線に接する。
//   ★モーターは ω = 1 に下げさせる。既定の 12 rad/s だと基準円の周速が 12 m/s で、
//     ラックは 0.5 秒もたたずに止めへ当たる（実測：30 tick 目にはもう止めに着いていた）。
//     1 rad/s ＝ 1 m/s で、止めまでの 1.2m を 1.2 秒かけて進む。
