// ── 87 計算を軽くする（スリープと遠方の凍結）──────────────────────
//   ★どちらも「計算を省く」しかけで、ときどき本当の動きまで止めてしまう、を見せる。
//   ★スリープ：4.8 cm/s より遅い状態が 0.6 秒続いた物体を眠らせる（sleep.js の SLEEP_LIN_TH・
//     SLEEP_TIME_TH）。摩擦 0 の箱を 0.3° だけ傾いた地面に置くと、加速度 g·sin0.3° = 0.05 m/s² で、
//     しきい値の速さに届く前に眠ってしまう。実測（10秒）：スリープあり 2px で止まる／
//     なし 2.57m 滑る。0.5° なら眠る前に速くなり、スリープありでも 4.3m 滑る＝ぎりぎりの題材。
//   ★遠方の凍結：画面の端からこの距離より外へ出た物体の計算を止める（ground.js の
//     updateFrozenBodies。描画のループで判定）。3m にすると、右へ転がって画面を出た球が
//     端から 3m で止まり、見に行くとまた転がる（実測）。
function demoTut2Sleep() {
  const gy = tutBegin();
  setGroundAngle(0.3);
  const A = tutBody({ type:'box', x:tutScreenX(700), y:gy - 25, w:60, h:40, mass:1, friction:0, frictionStatic:0,
    fillColor:'#42a5f5' });
  const B = tutBody({ type:'circle', x:tutScreenX(820), y:gy - 22, radius:20, mass:1, fillColor:'#ef5350' });
  B.vx = 300;                                          // [px/s] = 3 m/s
  demoLabel(A.x - 10, gy - 100, 'A', '#eceff1', 26);
  demoLabel(B.x - 10, gy - 100, 'B', '#eceff1', 26);
  tutText('87 計算を軽くする（スリープと遠方の凍結）', [
    '地面はほんの少し（0.3°）左へ下がっている。A は摩擦 0 の箱',
    '1. {btn-play} → A は動かない。B は右へ転がって画面を出る。戻す',
    '2. 上の シミュレーション →「シミュレーション設定」の',
    '　 「スリープ有効」を外す',
    '3. {btn-play} → A がゆっくり左へ滑り出す',
    '　 （ほとんど止まっている物を眠らせて計算を省くしかけ。',
    '　 　とてもゆっくりな動きは、眠らされて消えることがある）',
    '4. 同じ窓の「遠方を凍結」を 3 にして {btn-play}',
    '　 → B は画面の右から 3 m 出た所で止まる',
    '　 （画面の右下に「凍結 1」と出る）',
    '5. 右ドラッグで右へ見に行くと、B はまた転がり出す',
    '',
    '（どちらの設定も、別のデモを開くと元に戻る）']);
}
