// ════════════════════════════════════════
//   ★見せたいのは「**温度は平均であって、実際には速い分子も遅い分子もいる**」の一点。
//     そのために**全部の分子を同じ速さで置いて始める**。分布は仕込みではなく衝突の
//     結果だ、と言えるのはこの始め方だけである（既定の molSeedVelocity は最初から
//     マクスウェル分布で撒くので、そのまま出すと「そう作ったから」で終わってしまう）。
//   ★速さの分布計（spdmeter.js）を箱の内側いっぱいに1つ置く（数えるのは気体分子）。
//     理論の曲線は**2次元のマクスウェル分布** f(v) ∝ v·exp(−mv²/2kT)（＝レイリー分布）で、
//     画面の中が2次元だからで、molecule.js の「次元について」の★と同じ話。本文に断る。
//   ★**温度は変わらない**。壁は完全弾性で、分子どうしの衝突も弾性なので、運動エネルギーの
//     合計は動かない。変わるのは「その分けかた」だけ。実測（1200個・20℃相当の速さ
//     417m/s で開始）：
//         0秒   全部 417 m/s（棒が1本だけ）           温度 20.0℃
//         1秒   山ができ始める（幅が 0→±150 m/s）    温度 20.0℃
//         3秒   ほぼ理論の曲線に重なる                温度 20.0℃
//         10秒  重なったまま。ゆらぎだけが残る        温度 20.0℃
//     ＝ 温度（＝速さの2乗の平均）は6桁動かないのに、分布は数秒で変わりきる。
//   ★箱は『不可逆変化』と同じ寸法・同じ作法（完全弾性・摩擦0・断熱）。壁が反発 0.4 だと
//     分子が当たるたびにエネルギーを取られ、温度が下がりながら分布が育つことになる。
