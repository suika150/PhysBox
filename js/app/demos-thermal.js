// ════════════════════════════════════════
//  熱力学 ▸ 熱とエネルギー ▸ 状態変化と潜熱
// ════════════════════════════════════════
//   ★物質を作る粒を〇で表した**模型**である。分子運動論の分子（particles の 'gas'）では
//     なく、ふつうの剛体の円とばねで組む。分子のほうは「結びつき」を持てないからで、
//     molecule.js は完全弾性衝突だけを解く（ばねも引力も持たせない。持たせると分子
//     運動論が壊れる ── molecule.js 冒頭の注）。潜熱は結びつきをほどく仕事の話なので、
//     結びつきを持てる部品＝物体とばねの側で作るしかない。
//   ★**3つの箱で違うのはばねの強さだけ。** 粒の数・重さ・大きさ・初めの並び・初めの
//     速度まで、3箱で1ビットも違わない（同じ配列を3回使い回している）。伝導のデモで
//     比熱と密度を揃えたのと同じ考えで、変える量が1つでないと何が効いたのか読めない。
//         固体 k=PH_K_SOLID ／ 液体 k=PH_K_LIQUID ／ 気体 ばね無し
//   ★開いた瞬間は3箱がまったく同じ絵になる（同じ格子・同じ速度で止まっている）。
//     これは欠点ではなく、▶実行 の先で出る違いが全部ばねから来ていることの証拠になる。
//   ★**初速の合計と、重心まわりの角運動量の合計を 0 にしてある。** 揃えないと格子が
//     まるごと流れて壁にぶつかり、見たい「定位置で震える」が壁との衝突に埋もれる
//     （まるごと回りもする）。これは慣性系の選び方と重心を止める話であって運動の細工
//     ではない：引いたぶんは最後に全体を1つの係数で伸ばし直し、運動エネルギー＝温度を
//     3箱とも同じ値へ戻している。
//   ★ばねの減衰は 0、粒どうしと壁の反発は 1、摩擦は 0。どれか1つでも既定のままだと
//     エネルギーが減る＝**放っておくと温度が下がる**。この模型の主張は「温度は同じ
//     なのに状態が違う」なので、そこが減っては話が壊れる。
//   ★☆**この模型ではばねは切れない。** 実行しても固体が融けたり液体が沸いたりはしない。
//     この系に状態変化そのものの機構が無いためで、3つを並べて見くらべる図として
//     作ってある。本文にもそう書くこと（「融ける様子が見られる」と思わせない）。
//     潜熱は「そのばねをほどくのに要る仕事」として本文で読ませる。
//   ★**ばねは縦横だけでなく斜めにも張る**（4近傍＋対角＝1粒あたり最大8本）。縦横だけの
//     格子は角度を拘束しないので、**いくら硬くしても折り畳める**（せん断に対する復元力が
//     ゼロなので、硬さを上げても震えが小さくなるだけで格子は保てない）。
//     実測（k=300・30秒。dev＝各粒が自分の定位置から離れた距離のRMS）：
//         対角あり dev 4.5px（最大 6.1）  対角なし dev 11.9px（最大 20.6）
//     結晶の結合に向きがあることに対応している。3箱とも同じ張り方なので
//     「変えるのはばねの強さだけ」も保たれる。
//   ★**粒はほとんど触れ合う大きさにする**（直径 40px に対し間隔 48px）。液体のばねは
//     弱いので、粒が小さいとかたまりが自分のばねに引かれて潰れる。
//     実測（k=8・30秒。Rg＝かたまりの広がり。格子のときは 75.9px）：
//         半径20px  Rg 74.3〜91.0  ← 格子より縮まない＝体積が保たれている
//         半径 8px  Rg 45.1〜73.0  ← 6割まで潰れる
//     体積を決めているのはばねではなく粒どうしがぶつかることのほう＝実物の液体と同じ。
//   ★ばね定数はこの3つ（30秒の時間平均。dev は間隔 48px に対する割合）：
//         固体 k=300  dev  4.5px（間隔の 9%）  Rg 74.0〜77.6  ＝ 定位置で震える
//         液体 k=8    dev 37.2px（間隔の78%）  Rg 74.3〜91.0  ＝ 動き回るが離れない
//         気体 k=0    dev127.1px              Rg100.6〜134.2 ＝ 箱いっぱいに広がる
//     固体の 9% は融解のめやす（リンデマン則の 10〜15%）のすぐ下で、教科書の
//     「定位置のまわりで振動する」がそのまま出ている値である。**振れ幅を大きくして
//     見やすくしない**：大きくした時点でそれは固体ではなくなる。
//   ★30秒後に残る全エネルギー（運動＋ばね。100tick の時間平均）は
//     固体 0.994／液体 0.937／気体 1.000。気体は厳密に保存する。
//     ☆2026-09-27 まで固体はここで**爆発していた**（100tick 1.04 → 500tick 4.7 →
//       800tick 2274 倍。粒が箱を飛び出して隣の箱まで荒らす）。ばねの力を1サブステップ
//       まるごと接触のあとに足していたため、粒が反発で跳ね返るたびに誤差が溜まっていた。
//       ばねを前後半分ずつにして止めた（slinky.js の applyIdealSprings の★）。
//     ☆このデモを作る途中で、**反発 1 の物体どうしがぶつかるだけでエネルギーが消える**
//       ことが分かり、エンジン側を直した（js/core/units.js の restitutionVelTh の★）。
//       直す前はここが 気体 0.00／液体 0.04 で、そもそも成立しなかった。
const PH_WALL   = 14;      // [px] 箱の壁の厚み
const PH_HW     = 170;     // [px] 箱の内半幅
const PH_HH     = 145;     // [px] 箱の内半高
const PH_GAP    = 50;      // [px] 箱と箱のあいだ
const PH_NSIDE  = 4;       //      格子の一辺（4×4＝16個）
const PH_PITCH  = 48;      // [px] 格子の間隔＝ばねの自然長
const PH_R      = 20;      // [px] 粒の半径（上の★。間隔との差は 8px しかない）
const PH_M      = 0.5;     // [kg] 粒1個の重さ
const PH_V0     = 150;     // [px/s] 粒1個あたりの速さ（3箱とも同じ＝同じ温度）
const PH_K_SOLID  = 300;   // [N/m] 固体のばね（上の★で選ぶ）
const PH_K_LIQUID = 8;     // [N/m] 液体のばね（同上）

// 格子の座標と、3箱で使い回す初速。★上の★のとおり、合計の運動量と角運動量を 0 にし、
//   最後に1つの係数で運動エネルギーを n·½m·V0² へ戻す
function _phaseLatticeAndVelocities() {
  const n = PH_NSIDE * PH_NSIDE;
  const o = (PH_NSIDE - 1) * PH_PITCH / 2;
  const sites = [];
  for (let r = 0; r < PH_NSIDE; r++) for (let c = 0; c < PH_NSIDE; c++)
    sites.push({ x: c * PH_PITCH - o, y: r * PH_PITCH - o });
  const v = [];
  for (let i = 0; i < n; i++) {
    const a = Math.random() * Math.PI * 2;
    v.push({ x: Math.cos(a) * PH_V0, y: Math.sin(a) * PH_V0 });
  }
  let sx = 0, sy = 0;
  for (const q of v) { sx += q.x; sy += q.y; }
  for (const q of v) { q.x -= sx / n; q.y -= sy / n; }
  let L = 0, I = 0;
  for (let i = 0; i < n; i++) {
    const s = sites[i];
    L += s.x * v[i].y - s.y * v[i].x;
    I += s.x * s.x + s.y * s.y;
  }
  const w = I > 0 ? L / I : 0;
  for (let i = 0; i < n; i++) { const s = sites[i]; v[i].x += w * s.y; v[i].y -= w * s.x; }
  let e = 0;
  for (const q of v) e += q.x * q.x + q.y * q.y;
  const g = e > 0 ? Math.sqrt(n * PH_V0 * PH_V0 / e) : 1;
  for (const q of v) { q.x *= g; q.y *= g; }
  return { sites, v };
}

// 箱1つぶん。k=0 でばね無し（気体）
function _phaseBox(cx, cy, k, col, sites, vel) {
  //   ★4枚を図形和で1つの物体にする（demo-kit.js の demoUnion）。4枚とも性質は同じ。
  const walls = [];
  const wall = (dx, dy, ww, hh) => { const b = new Body({
    type:'box', x:cx + dx, y:cy + dy, w:ww, h:hh, isStatic:true, conduct:0, heatCap:0,
    restitution:1, friction:0, frictionStatic:0,
    fillColor:'#37474f', strokeColor:'#b0bec5', strokeWidth:2 }); walls.push(b); return b; };
  const ww = PH_HW + PH_WALL/2, hh = PH_HH + PH_WALL/2;
  wall(0, -hh, 2*PH_HW + 2*PH_WALL, PH_WALL);
  wall(0,  hh, 2*PH_HW + 2*PH_WALL, PH_WALL);
  wall(-ww, 0, PH_WALL, 2*PH_HH);
  wall( ww, 0, PH_WALL, 2*PH_HH);
  demoUnion(walls);
  const dots = [];
  for (let i = 0; i < sites.length; i++) {
    const b = new Body({ type:'circle', x:cx + sites[i].x, y:cy + sites[i].y,
      radius:PH_R, mass:PH_M, restitution:1, friction:0, frictionStatic:0,
      conduct:0, heatCap:0, fillColor:col.fill, strokeColor:col.stroke, strokeWidth:2 });
    b.vx = vel[i].x; b.vy = vel[i].y;
    objects.push(b); dots.push(b);
  }
  // ★4近傍＋対角。対角の自然長は √2 倍にする（そこを PH_PITCH のままにすると、
  //   組んだ瞬間から対角のばねが縮んでいて格子が自分から歪む）
  const DIAG = Math.SQRT2 * PH_PITCH;
  if (k > 0) for (let r = 0; r < PH_NSIDE; r++) for (let c = 0; c < PH_NSIDE; c++) {
    const i = r * PH_NSIDE + c;
    // ★格子の結合はコイルで描かない（showCoil:false）。原子間の距離は 40px 前後しかなく、
    //   そこに巻きを描くと格子全体が渦の集まりに見えて、原子の並びのほうが読めなくなる。
    const link = (j, L) => demoSpring({ bodyA:dots[i], bodyB:dots[j],
      anchorAx:0, anchorAy:0, anchorBx:0, anchorBy:0,
      restLength:L, stiffness:k, damping:0, showCoil:false, color:col.spring });
    if (c + 1 < PH_NSIDE) link(i + 1, PH_PITCH);              // 右どなり
    if (r + 1 < PH_NSIDE) {
      link(i + PH_NSIDE, PH_PITCH);                           // 下どなり
      if (c + 1 < PH_NSIDE) link(i + PH_NSIDE + 1, DIAG);     // 右下（対角）
      if (c > 0)            link(i + PH_NSIDE - 1, DIAG);     // 左下（対角）
    }
  }
  return dots;
}

