//     ディスプレーサ式（β型）は「1つの気体が高温部と低温部を行き来する」ので、
//     気体室が2つの空間を持つ必要があるが、α型なら**2つの気体室を管でつなぐ**だけで
//     同じことになる（gas.js の solveGasLinks）。
//   ★**連結棒は「硬いばね・減衰0」にする。棒ジョイントでは回らない。** 実測（気体なし・
//     摩擦なしのクランク機構を ω=6 で回して 30秒）：
