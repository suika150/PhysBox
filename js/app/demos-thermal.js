// ════════════════════════════════════════
//  熱力学 ▸ 熱の移動 ▸ 対流
// ════════════════════════════════════════
//   ★味噌汁のおわん。下の**真ん中だけ**を熱し、おわんの壁で冷やす。温まった水が
//     軽くなって真ん中をまっすぐ上り、端で冷えて壁を下り、下で真ん中へ戻る。
//     **循環そのものはどこにも書いていない**：粒子は自分の温度で自分にかかる重力を
//     変えるだけで（particles.js ①のブシネスク近似）、上昇も下降も渦もそこから出る。
//   ★下の真ん中を熱すのが要点。左右の壁で熱／冷やす形（前の版）でも循環はするが、
//     「真ん中で上がって端で下りる」という、鍋でも味噌汁でも見慣れた形にはならない。
//     実測（乱数固定・900tick 立ち上げ後 300tick の時間平均、鉛直速度 vy [px/s]。
//     負＝上昇。おわんの幅を7列に分けて左から）：
//         +3.9  +5.2  −3.7  −16.3  +2.5  +5.8  +2.9
//     ＝ 端は下向き、真ん中は上向き。中央の柱が少し左に寄るのは実物の煙と同じで、
//       プルームの位置は揺らぐ（時間平均でも完全な左右対称にはならない）。
//   ★読みどころは「切ると止まる」。熱膨張を切った対照（SPH.expandGain=0）では
//     vy がどの列も ±1.0px/s 以下＝流れが立たず、しかも**上下の温度が逆転する**：
//         上/下の平均温度   40倍 32.8℃ / 26.9℃   ←→   0倍 20.7℃ / 30.0℃
//     熱が下にたまったまま上がってこない。デモの中で切り替える手段は無いので、
//     本文にこの数字を書いておく。
//   ★ふたはしない（水面は自由表面）。ふたを付けても意味が無い：水は重力で下に落ち着き
//     天井に触れないので、ふたの温度を 20℃ に固定しても結果が 1 ビットも変わらなかった
//     （粒子↔物体の熱は「押し出しが起きた＝触れている」ときだけ動くため）。
//     ＝ 冷やす役はおわんの壁がぜんぶ受け持っている。
//   ★下の壁の両脇は断熱にする。ここまで熱すると鍋底ぜんぶが熱源になり、
//     真ん中の柱が立たずに一面から泡立つ形になる。
//   ★色の範囲は 20〜45℃ にする。80℃ まで取ると、実際に出る温度（中央値 27℃・
//     上位1割で 33℃）が色帯の下端に固まって、ぜんぶ青に見える。
const CV_HW = 230, CV_HH = 130, CV_T = 18;   // [px] おわんの内半幅・内半高・壁厚
const CV_HOT = 70;                           // [px] コンロ（熱する範囲）の半幅
const CV_FILL = 0.86;                        // 水深／内高（上に自由表面のぶんを空ける）
const CV_TRACERS = 4;                        // 軌跡を付ける水の数（下の★）
// ★軌跡を残す秒数。真ん中を上りきるのに 12 秒前後、一周には 30 秒あまりかかるので、
//   既定の 5 秒では短い尾にしかならない。40 秒あれば「上って・広がって・壁を下りて・
//   戻る」が1本の線として画面に残る。長くしすぎると古い周回と重なって団子になる。
