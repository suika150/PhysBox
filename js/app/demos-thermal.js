//  ══ この分野に固有の事情（先に読む）════════════════════════════════
//
//  ① **剛体は1つにつき温度を1つしか持たない**（Body.temp）。棒の中の温度勾配は
//     表せないので、「熱が伝わっていく」を見せるには **ブロックを何個も並べる**。
//     これは手抜きの近似ではなく、この系の熱伝導が「接触しているペアの取引」
//     （thermal.js の linkBodyBodyHeat）として定義されていることの素直な帰結。
//     並べたブロックは手でも置けるので「手で作れる部品だけで組む」からも外れない。
//
//  ② **world.thermalRate（既定 50000）はデモごとに選び直す。** 実物の熱伝導は
//     教材で眺めるには遅すぎるので倍率が掛かっているが、既定のままだと今度は
//     金属が速すぎる（実測：k=237 のブロック4個は 15 秒で全部 200℃ に到達＝
//     伝わる過程が1コマも見えない）。材質どうしの比は倍率を変えても保たれるので、
//     「見たい過程が画面の中の時間に収まるか」だけで選んでよい。
//
//  ③ **摩擦熱で温度は上がらない。** 上がるが、桁が違う。運動エネルギーを全部
//     熱に変えても ΔT = v²/(2c) で、鉄（c=450）が 3m/s で止まっても 0.01℃。
//     これは実装の弱さではなく実物がそうで、ジュールが精密な温度計を要した理由
//     そのもの。温度グラフは自動で縦軸を合わせる（tempgraph.js:319）ので、
//     0.01℃ の上がりもグラフには出る。**数字を隠さずそのまま読ませること。**
//
//  ④ 水は SPH、気体分子は分子運動論と、**別のソルバで動く**（particles.js の注）。
//     混ぜて使ってよいが、水を分子として説明しないこと（1粒子は 0.63kg の水の塊）。

// ════════════════════════════════════════
//  熱力学 ▸ 熱とエネルギー ▸ 熱量保存
// ════════════════════════════════════════
//   ★80℃の鉄を20℃の水へ入れて、両方が同じ温度で止まるまでを見せる。
//   ★寸法は「行き着く先が 30℃ ちょうど」になるように決めてある：
//       水  180粒子 × 0.63kg = 113.4kg、c=4182 → 熱容量 474 kJ/K
//       鉄  0.73m角 × 奥行0.05m × 7870 = 210kg、c=450 → 熱容量 94.4 kJ/K
//       T = (474×20 + 94.4×80) / (474 + 94.4) = 29.96℃
//     ＝「水のほうが熱容量が5倍大きいので、20℃側へ大きく寄る」が数字で読める。
//     鉄を大きく見せているのはそのため（同じ体積の水より鉄は8倍重いのに、
//     熱容量では水に負ける＝比熱の差がそれだけ効いている、という読みどころ）。
//   ★コップは断熱にする（conduct:0）。熱の出口を1つにしないと「失った熱＝得た熱」が
//     成り立たなくなり、このデモの主張そのものが崩れる。
//   ★容器は「水＋沈めた鉄」がぜんぶ収まる大きさにする。水を入れてから鉄を落とすと
//     鉄の体積ぶん水位が上がるので、そのぶんの余裕（フリーボード）が要る。
//     実測：内寸 200×110px に水180粒子（22,680px²）を入れた時点で既に容器の
//     容積 22,000px² を超えており、鉄（5,329px²）を落とすと外へこぼれた。
//     こぼれた水は鉄に触れないまま冷たく残り、「液体（平均）」の系列を引き下げて
//     平衡に届くのが遅く見える（60秒かけて 29.8℃）。
//     内寸 240×150px＝36,000px² なら 水22,680＋鉄5,329＝28,009 で、まだ 33px 余る。
//   ★壁を厚くしてある。SPH の水は、重い物を沈めると静水圧で容器の継ぎ目から
//     押し出される。落とす高さを 90→10px にしても漏れは 24→19 粒子としか変わらず
//     （＝衝撃ではなく静水圧）、厚み 14→24px で 22→11 粒子に半減した。
//     ☆漏れそのものは particles.js 側で断った（押し出しは静止した物体を最後に解く＝
//       重い鉄が水を壁の中へ押し込んだまま終わらない）。実測 21.0→0.0 粒子。
//       厚みはこのまま残す：薄い壁は「入口が分からない水を最寄りの面へ出す」経路に
//       戻ったときの逃げ道になるので、厚いほうが二重に安全。
//     ☆着底した鉄の下に残る1列（6粒子）も、SPH._squeezeOut が横へ逃がす。
//       実測：鉄の中に居続けた粒子は 5.91→0.07（30秒の時間平均。0.07 は沈む途中の
//       0.4秒だけ）。鉄は水の底に直に座り、水は左右へ押しのけられる。
const HB_IW = 120, HB_IH = 150, HB_T = 24;    // [px] コップの内半幅・内高さ・厚み
const HB_STEP = 11;                           // [px] 水の粒子の間隔（restArea 126px² ＝ 11.2px）
const HB_BLOCK = 73;                          // [px] 鉄ブロックの一辺
function demoHeatBalance() {
  const gy = ground.y;
  resetDemoWorld();
  world.sleeping = false;
  world.thermalOn = true;
  world.thermalViz = true;                    // 温度で色をつける（表示だけ）
  world.thermalVizMin = 0; world.thermalVizMax = 90;
  world.waterSmooth = true;                   // 水を塊で描く（見た目だけ。world.waterSmooth の★）
  // ★熱の伝わる速さは既定（50000）の3倍にする。壁の鏡像（particles.js の
  //   _measureWalls）を入れて水が静かになったぶん、**水がひとりでに掻き混ざらなく
  //   なった**ため。実測：水の平均速さ 40.6 → 5.7px/s。以前は鉄のまわりで温まった
  //   水を数値振動が運び去っていて、60秒で平衡に届いていたのはそのおかげだった。
  //   静かな水では熱は伝導だけで広がるので、同じ倍率だと 180 秒かかる。
  //   ☆倍率は行き着く温度に効かない（thermal.js の注）。実測でも熱量の合計は
  //     どの倍率でも 100.0% のまま動かず、平衡は 30℃ で変わらない。
  //     150000 で 30秒 30.9/29.8℃・45秒 30.2/29.9℃・60秒 30.0/29.9℃ と、
  //     直す前の見え方（60秒で 30.1/29.9℃）に戻る。
  world.thermalRate = 150000;
  updateGroundTerrain(true);
  // ── 断熱のコップ ────────────────────────────────────────
  objects.push(new Body({
    type:'polygon', x:0, y:gy - HB_T, isStatic:true, mass:0,
    conduct:0, heatCap:0,                      // ★断熱（熱の出口を作らない）
    friction:0.4, frictionStatic:0.5, restitution:0,
    verts:[{ x:-(HB_IW+HB_T), y:-HB_IH }, { x:-HB_IW, y:-HB_IH }, { x:-HB_IW, y:0 },
           { x:HB_IW, y:0 }, { x:HB_IW, y:-HB_IH }, { x:(HB_IW+HB_T), y:-HB_IH },
           { x:(HB_IW+HB_T), y:HB_T }, { x:-(HB_IW+HB_T), y:HB_T }],
    fillColor:'#37474f', strokeColor:'#b0bec5', strokeWidth:2.5, label:'断熱容器' }));
  // ── 水 20℃（20列 × 9段 = 180粒子）──────────────────────
  const floorY = gy - HB_T;
  for (let iy = 0; iy < 9; iy++) for (let ix = 0; ix < 20; ix++)
    particles.push(new Particle(-HB_IW + 10 + ix*HB_STEP, floorY - 6 - iy*HB_STEP, 'fluid'));
  for (const p of particles) p.T = C2K(20);
  // ── 80℃の鉄ブロック ────────────────────────────────────
  const iron = new Body({
    type:'box', w:HB_BLOCK, h:HB_BLOCK, x:0, y:floorY - HB_IH - 90, density:7870,
    heatCap:450, conduct:80, temp:C2K(80),     // 鉄の実測値
    friction:0.4, frictionStatic:0.5, restitution:0,
    strokeColor:'#eceff1', strokeWidth:2, label:'鉄 80℃' });
  iron.setMass(iron.massFromDensity());
  objects.push(iron);
  // ── グラフ（鉄と水の2系列。水の系列は tempGraphNew が今のシーンから足す）──
  //   ★このデモは温度グラフの2本を読ませることそのものが本題なので、窓を既定より
  //     横に長くする（段は1つしかないので、縦はそのぶん詰めてよい）。
  //     広げたぶんコップは左へ寄せる（下の setDemoCam の★）。
  moveDemoGraphTop(sizeDemoGraph(tempGraphNew([iron.id]), 460, 360));
  // ── 説明 ─────────────────────────────────────────
  // ★視点を右へ 60px ずらす＝コップと鉄が画面の左寄りに来る。本文は画面の左上に
  //   貼りつくので一緒には動かず、広げたグラフの窓（右上）と題材が重ならなくなる。
  setDemoCam(60, 0.9);
  const p = demoTextTopLeft();
  demoTitle(p.x, p.y, '熱量保存');
  demoNote (p.x, p.y + 54,
    '80℃ に熱した鉄のかたまりを、20℃ の水へ入れる。\n'
  + '容器は断熱なので、熱の行き先は水しかない。\n'
  + '\n'
  + '【手順】▶実行 を押して、温度グラフの2本を見る。\n'
  + '・鉄は下がり、水は上がり、30℃ で出会って止まる\n'
  + '・鉄が失った熱と、水が得た熱は同じ量\n'
  + '\n'
  + '真ん中の 50℃ ではなく 20℃ 寄りで止まるのは、\n'
  + '水の熱容量が鉄の5倍あるから。鉄は水の8倍重い\n'
  + 'のに、比熱が 450 と 4182 で9倍違う。');
}

// ════════════════════════════════════════
//  熱力学 ▸ 気体分子運動論 ▸ ブラウン運動
// ════════════════════════════════════════
//   ★花粉の粒（大きい円）を気体分子の中に置くだけ。ふらつきは「そう見えるように
//     動かしている」のではなく、分子が四方から叩く力積の釣り合いが偶然崩れた
//     ぶんがそのまま出ている（molecule.js の _bounceBody が衝突の瞬間に渡す）。
//   ★重力は 0 にする。ブラウン運動は重力とは無関係なので、落ちてしまうと
//     見たいものが沈殿に隠れる。
//   ★粒の重さを2つ並べるのが読みどころ。等分配則で ½m⟨v²⟩ は重さによらず同じなので、
//     速さは 1/√m になる。実測（箱±450px・分子1500・60秒の時間平均）：
//         0.2kg 429 / 0.5kg 248 / 1kg 193 / 2kg 141 / 5kg 81 px/s
//     1/√m の予測は 429 / 271 / 192 / 136 / 86 で、ほぼそのまま乗っている。
//   ★「軽いほうが遠くまで動く」とは書かないこと。変位は箱の大きさで頭打ちになり、
//     実測でも RMS 変位は 0.5kg が 242px・5kg が 235px でほとんど差が無かった。
//     差が出るのは速さのほう。
//   ★箱を大きくとってあるのは、狭いと粒が壁に貼りついて動かなくなるからである。
//     分子は粒と壁のすき間に入れないので、壁に触れた粒は片側からしか叩かれず、
//     隅へ押し込まれたきり出られない（実測：箱±300px・分子900 では 5kg の粒が
//     30秒で隅に到達し、以後 60秒まで運動エネルギー 0.00J のまま停止した）。
//     ±450×±240・分子1500 なら、5kg でも 60秒後の v_rms が 49px/s と動き続ける。
//     ☆これは実物にもある効果（排除体積による枯渇力）だが、ここでは分子1個が
//       粒の 1/17 の大きさしかないので桁違いに強く出る。実物の花粉と空気分子は
//       10⁴ 倍違うので貼りつかない。
//   ★壁は完全弾性・摩擦0にしてある（Body の既定は反発 0.4）。既定のままだと、
//     粒が壁に当たるたびにエネルギーが壁へ吸われ、分子がそれを補い続けるので
//     気体だけが冷えていく。
//     実測（60秒）：気体の温度は 20.0℃ → 19.8℃、分子の運動エネルギーは +2.0%
//     （＝正味の漏れなし。+2% は置いた直後に重なりを押し出すぶんの立ち上がり）。
//     ☆かつてここは 20℃ → −15℃ まで冷えていた。原因は壁でも粒の数でもなく、
//       molecule.js が弾性衝突の法線に「押し出した変位の向き」を使っていたこと
//       だった（掃引で戻したときは面の法線とずれ、なめらかな円にもトルクが立つ）。
//       直したので、気体の温度グラフを出しても読める状態になっている。
const BR_HW = 450;            // [px] 箱の内半幅
const BR_HH = 240;            // [px] 箱の内半高（横長にして、説明文の下に収める）
const BR_WALL = 20;           // [px] 壁の厚み
const BR_MOLS = 1500;         // 分子の数
function demoBrownianMotion() {
  resetDemoWorld();
  setDemoGravity(0);          // ★無重力（ブラウン運動は重力と無関係）
  world.sleeping = false;
  world.thermalOn = true;
  world.thermalViz = false;
  updateGroundTerrain(false); // 地面なし
  // ── 密閉した箱（下の壁の外側が地面の高さに来るように置く）──────
  const cy = ground.y - BR_HH - BR_WALL;
  // ★壁は完全弾性・摩擦0にする。既定のままだと反発 0.4 で、粒が壁に当たるたびに
  //   エネルギーが壁へ吸われ、分子がそれを補い続けて気体だけが冷える。
  //   ★4枚を図形和で1つの物体にする（demo-kit.js の demoUnion）。4枚とも性質は同じ。
  const walls = [];
  const wall = (dx, dy, ww, hh) => { const b = new Body({
    type:'box', x:dx, y:cy + dy, w:ww, h:hh, isStatic:true, conduct:0, heatCap:0,
    restitution:1, friction:0, frictionStatic:0,
    fillColor:'#37474f', strokeColor:'#b0bec5', strokeWidth:2 }); walls.push(b); return b; };
  const ww = BR_HW + BR_WALL/2, hh = BR_HH + BR_WALL/2;
  wall(0, -hh, 2*BR_HW + 2*BR_WALL, BR_WALL);
  wall(0,  hh, 2*BR_HW + 2*BR_WALL, BR_WALL);
  wall(-ww, 0, BR_WALL, 2*BR_HH);
  wall( ww, 0, BR_WALL, 2*BR_HH);
  demoUnion(walls).label = '箱';
  // ── 気体分子 20℃ ───────────────────────────────────
  for (let i = 0; i < BR_MOLS; i++) {
    const p = new Particle((Math.random()*2-1)*(BR_HW-12),
                           cy + (Math.random()*2-1)*(BR_HH-12), 'gas');
    p.T = ROOM_K; molSeedVelocity(p, p.T);
    particles.push(p);
  }
  // ── 花粉の粒（重さだけが違う2つ）────────────────────────
  const GRAINS = [
    { m:0.5, x:-200, fill:'#ffd54f', stroke:'#fff59d', name:'軽い粒 0.5kg' },
    { m:5.0, x: 200, fill:'#ef9a9a', stroke:'#ffcdd2', name:'重い粒 5kg'  },
  ];
  for (const g of GRAINS) {
    const b = new Body({
      type:'circle', x:g.x, y:cy, radius:26, mass:g.m,
      friction:0, frictionStatic:0, restitution:1, conduct:0, heatCap:0,
      fillColor:g.fill, strokeColor:g.stroke, strokeWidth:2, label:g.name });
    b.tracerEnabled = true;          // ★道すじそのものが読みどころ
    b.tracerColor = g.fill;
    b.tracerDuration = 60;
    objects.push(b);
  }
  // ── 説明 ─────────────────────────────────────────
  setDemoCam(0, 0.55);
  const p = demoTextTopLeft();
  demoTitle(p.x, p.y, 'ブラウン運動');
  demoNote (p.x, p.y + 54,
    '20℃ の気体分子の中に、目に見える大きさの粒を\n'
  + '2つ置いた。大きさは同じで、重さだけが違う\n'
  + '（0.5kg と 5kg）。重力は 0 にしてある。\n'
  + '\n'
  + '【手順】▶実行 を押して、粒の残す道すじを見る。\n'
  + '・粒はどちらも、行き先を決めずにふらふら動く\n'
  + '・軽いほうが3倍ほど速い（重いほうはゆっくり）\n'
  + '・どちらも箱じゅうを回るので、行ける範囲は同じ\n'
  + '\n'
  + '粒を動かす仕掛けは何も入れていない。四方から\n'
  + '叩く分子の数がたまたま釣り合わなかったぶんが、\n'
  + 'そのまま粒の動きになっている。速さが 1/√重さ に\n'
  + 'なるのは、叩かれて受け取るエネルギーが重さに\n'
  + 'よらず同じだから（エネルギー等分配の法則）。');
}

// ════════════════════════════════════════
//  熱力学 ▸ 熱とエネルギー ▸ 不可逆変化
// ════════════════════════════════════════
//   ★赤と青に印を付けた気体を左右に分けて置くだけ。実行すると混ざり、混ざったものが
//     自分から赤青に分かれ直すことは、待っていても起きない。
//   ★**印を付けるだけ**で、赤い分子と青い分子は物理的に同じ気体である（色は
//     particles.js の particleColor の注のとおり質量にも比熱にも効かない）。そう書くこと。
//     「2種類の気体」と言ってはいけない。この系の分子は1種類しかない。
//   ★**真ん中に仕切りを立て、小さな穴（IR_HOLE=20px）だけを開けておく。** 分子が
//     行き来できるのはその穴1つだけになり、混ざるのに時間がかかる＝過程が追える。
//     ☆かつてはここに「仕切りを置かない」と書いてあった。理由は「置くと "クリックして
//       Delete で消す" 操作が要り、主題（混ざること）から目を逸らす」というもので、
//       その理由は今も正しい。**穴を開けた仕切りは外す必要がない**ので、その難点だけが
//       消えて、初期状態が「本当に分かれている」ことのほうが取れる。
//       実行するまで分子は動かないという性質も変わらないので、実行した瞬間が t=0 なのも
//       そのまま（グラフや目視の起点がはっきりする）。
//   ★**仕切りは穴以外からは1個も漏れない。** 隙間 0 の仕切りで対照を取り、60秒回して
//     左半分に残る赤が 1.000 のまま動かないことを確かめてある（分子の速さは 20℃ で
//     σ=797px/s ＝ 1サブステップ 3.3px しか進まず、壁の厚み 20px を跳び越せない。
//     加えて particles.js の _collideBodyPoly が掃引つきで「入ってきた面」へ戻す）。
//     ＝「そこしか通れない」を演出ではなく実測で言える。
//   ★液体（SPH）では作れない。SPH に分子拡散は無く、色を分けて並べても混ざらない。
//     実測（760粒子・60秒、左半分に残る赤の割合。0.50＝完全に混合）：
//         仕切りを外すだけ 0.94→0.73 ／ 下から熱して対流 0.87→0.72 ／ 羽根で撹拌 0.64で頭打ち
//         気体分子（1400個）           0.75秒で染み合い、5秒で 0.50 に到達してそのまま
//     しかも水の 0.94→0.73 は拡散ではなく、非圧縮を保つための位置緩和の数値振動である
//     （赤が上・青が下へ系統的にずれる＝拡散の等方的な広がりに見えない）。
//     ＝ ここで液体を使うと、この系がいちばん避けている「数値の癖を物理として見せる」
//     ことになる。分子運動を解いている気体でだけ成り立つ。
//   ★穴の大きさは 20px にした（壁の高さ 370px の 5%）。振って測った
//     （乱数固定・分子1100個・左半分に残る赤の割合。1.00＝分離／0.50＝混合。
//      t はシミュレーション時間で、再生速度 1× ならそのまま実時間）：
