//         ばね 1e4・減衰0   ω 5.91〜6.00 を維持（棒の伸び ±0.55px）
//         ばね 1e5・減衰0   ω 5.92〜6.00 を維持（伸び ±0.07px）← これを使う
//         ばね 1e6・減衰0   発散（刻みに対して硬すぎる）
//     このデモそのままでも測り直した（ω=10 で始動して 30秒・時間平均の ω）：
//         ばね 1e5   1秒 7.08 → 5秒 6.16 → 10秒 13.1 → 30秒 16.1 rad/s（2.56回転/秒）
//         棒         1秒 1.85 → 5秒 0.14 → 30秒 0.14 rad/s（0.02回転/秒＝止まっている）
//     ★**棒は「回し続けると漏れる」**。最小の反例で確かめてある＝自由な2物体を棒で
//       つないで重心まわりに回すだけのダンベル（重力も地面も接触もなし＝理論上は
//       運動エネルギーが完全に保存する配置）。30秒後に残る運動エネルギー：
//           ω=1 rad/s・substeps 4    88.9%
//           ω=2 rad/s・substeps 4    66.7%
//           ω=4 rad/s・substeps 4    33.4%
//           ω=2 rad/s・substeps 8    80.0%
//           ω=2 rad/s・substeps 16   88.9%   ← ω=1・substeps 4 と同じ値
//       ＝ 抜ける量は **ω²×1サブステップの時間** で決まる。原因は離散化：位置を直線で
//       進めると棒は向心加速度のぶんだけ必ず伸び、棒はその「見かけの伸び速度」を毎
//       サブステップ0に潰す。潰したぶんの運動エネルギーがそのまま消える。硬いばねは
//       同じずれを弾性として貯めて返すので消えない（連結棒がばねなのはこのため）。
//     ★**ウォームスタート（力積の持ち越し）では直らない。** 等式拘束の射影は初期値を
//       見ないので、頭で打ち直した力積を直後の solve が同じだけ打ち消す。棒とヒンジの
//       両方に入れて実測したが、このデモもダンベルも1ビットも変わらなかった。
//     ★**XPBD（位置を直し、動いた量÷Δt で速度を作り直す）も試したが悪化した。**
//       ダンベル 30秒後の残存（ω=2・substeps 4）：
//           いまの解き方（潰す）        66.7%
//           位置の補正を速度に足す      50.0%
//           位置だけ直して速度を作り直す 50.0%
//       紙の上では弦÷Δt になって θ²/24 しか縮まないはずだが、実際は毎サブステップ
//       0.003% ずつ落ち続けた（速度を作り直す前後で測った）。棒だけを XPBD にしても、
//       同じ物体を触る接触・壁・案内・ピストンの投影が従来のままなので、噛み合って
//       いないのだと思われる。**エンジン全体を XPBD へ移す話**になるので手を引いた。
//       どちらも revert 済み。再挑戦するならこの3行の実測から始めること。
//     ☆現実的な逃げ道は substeps を上げること（抜ける量は ω²×サブステップ時間なので、
//       substeps 4→16 は ω を半分にしたのと同じ）。ただし全体が4倍重くなる。
//     ☆振り子のように ω が小さくて往復する使い方なら実害はない（二重振り子のデモは
//       30秒で −5.2%、単振り子は ±4% で増減）。回り続ける機構だけがこの穴に落ちる。
//   ★**始動には手回しが要る**。実物のスターリングと同じで、止まっているところからは
//     回り出さない。実測（400℃/20℃・蓋の摩擦15）：ω=0 のままだと 40秒たっても 0、
//     ω=10 で始動すると 30.4 rad/s（4.8回転/秒）まで上がって落ち着く。
//     ☆このデモの寸法（弾み車まで 520px）では、ω=10 で始動して 10秒 2.16回転/秒・
//       30秒 2.62回転/秒 に落ち着く（乱数固定・以下すべて 30秒の実測）。
//   ★**この装置からは熱効率を出さない。出せないから。** 以前ここには 16.0%（本文）と
//     9.1%（この★）という食い違う2つの数字が載っていたが、どちらも意味が無かった。
//     ☆16.0% は `ch.efficiency()` ＝ W / **Qin**。この Qin（高温室が吸った熱の総和
//       ≈778 kJ）には、蓋の摩擦が気体へ捨てた熱を恒温槽が毎サブステップ回収した分が
//       丸ごと混ざっている。熱力学の Qh は「高温源が正味で供給した熱」のほうで、
//       摩擦を仕分けして測ると 152.1 kJ（低温源へ 137.3 kJ、摩擦が捨てた熱は
//       高温室 41.2 ／ 低温室 64.0 ＝ 105.2 kJ）。
//     ☆**そもそもこの装置は外へ仕事を出していない。** 負荷は蓋の摩擦だけで、その熱は
//       gasAddHeat で気体へ戻り、恒温槽が両側から回収する（蓋も器も heatCap=0 なので
//       行き先が気体しかない）。取り出した仕事が全部その場で熱に戻り、しかも一部は
//       高温源へ返る以上、カルノーと比べられる η は定義できない。無理に指示効率を
//       出すと 105.2/152.1 ＝ 69.2% とカルノー 56.5% を超える。破れているのは
//       第二法則ではなく「熱機関として読む」前提のほう（外界の ΔS は +0.242 kJ/K で
//       ちゃんと正）。**熱効率を見せたいなら、仕事が気体へ戻らない外部負荷が要る。**
//     ☆**加えて、この回転数では刻みが粗すぎて帳簿が閉じない。** 2.57回転/秒 ＝
//       1周わずか 23tick。定常なら Rh − Rc は摩擦が捨てた熱 105.2 kJ と一致するはずが、
//       実測 14.8 kJ しか無い（1割の取りこぼし）。機構を外した最小の反例（2室を管で
//       つなぎ蓋を正弦で動かすだけ）で確かめると、この誤差は**1周の tick 数に反比例する
//       1次の時間刻み誤差**で、substeps には全く反応しない：
//           同温の対照（Th=Tc=20℃。正しければ W=0）
//             1周120tick → 1.29 kJ ／ 240tick → 0.65 ／ 480tick → 0.32
//           温度差あり（400℃/20℃）の η
//             1周120tick → 56.7% ／ 480tick → 56.5% ＝ カルノー 56.5% に収束
//       ☆ついでに分かったこと：**このモデルは可逆機関そのもの**。管を通る気体が内部
//         エネルギーを持ったまま瞬間移動する＝完全な再生器がタダで付いているので、
//         不可逆性が一つも無く、η はカルノーを下回るのではなく**一致する**。
//         「実機はカルノーに届かない」を見せる題材には、この気体室だけでは足りない。
//     ☆つないだ2室の圧力は完全には一致しない（実測 87.1 と 84.5 kPa ＝ 3%）。
//       物質量を分け直すのは tick の頭で、そのあとサブステップで体積が動くため。
//   ★**負荷は蓋とシリンダーの摩擦（気体室の damp）**で与える。実測（400℃/20℃・始動ω3）：
//         摩擦 0（無負荷）  ω 3 → 66 まで上がり続ける（止まらない）
//         摩擦 5           50.9 rad/s で落ち着く
//         摩擦 10          38.1 rad/s
//         摩擦 12          34.2 rad/s
//         摩擦 15          始動できない（ω=10 で回せば 30.4 で落ち着く）← これを使う
//         摩擦 20          止まる
//     背景摩擦（台の摩擦）で負荷を掛ける手もあるが、0.05 でも止まった（回転の制動が
//     効きすぎる）ので、蓋の摩擦のほうを使う。
//   ★**温度差が無いと回らない**ことを対照で確かめてある。両方 20℃ にすると、ω=20
//     （3.18回転/秒）で回してやっても、10秒 0.58 → 30秒 0.01 → 40秒 0.00回転/秒 で
