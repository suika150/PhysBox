// ════════════════════════════════════════
//   ★Cp − Cv = R（マイヤーの関係）は丸暗記されやすい式の代表だが、この系は**測れる**。
//     同じ気体を2つ並べ、**同じ出力の加熱器で同じ時間だけ温める**。片方はピストンを
//     固定（定積）、もう片方は自由（定圧）。入る熱は同じなのに、温度の上がりかたが違う。
//     差は気体がした仕事 W = PΔV = nRΔT へ行っている。
//   ★読ませたいのは「Cp が Cv より大きいのは、膨らむぶんの仕事を余計にしないと
//     いけないから」の一点。式を出す前に、**2本の線の傾きの違い**で先に見せる。
//   ★温度 – 時間のグラフを1枚開く（tempgraph.js。気体室は器ごとに1系列）。
//     器の札の温度だけだと「いまいくつか」しか読めず、**上がりかたの違い**＝このデモの
//     主題が、2つの数字を交互に見比べる暗算になってしまう。時間軸に並べると
//     「どちらも直線・傾きが違う」が1目で出る。P–T・V–T 図では代わりにならない
//     （横軸が時間でないので、そもそも2つの器の同じ時刻どうしを並べられない）。
//   ★実測（600 tick ＝ 10秒ぶんの全標本を最小二乗）：
//         定積  17.359 K/s（残差 1e-12 K ＝ 完全な直線。W=0 で Q が全部 ΔU へ行く）
